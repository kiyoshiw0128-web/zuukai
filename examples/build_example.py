"""見本のデッキ「会議を30分で終える」を作る。数字はすべて架空の例。

    python examples/build_example.py  →  examples/sample_会議を30分で終える.pptx
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "scripts"))

from zukai_core import CONTENT, Box, Deck, icon_clock, icon_doc, icon_person  # noqa: E402
from zukai_parts import (action_list, bars, before_after, decision_flow,  # noqa: E402
                         flow_steps, matrix_2x2, ratio_grid, role_cards, table, timeline)

SRC = "出典：架空の例（見本用の数字）"


def cover_art(sl, b: Box) -> None:
    icon_clock(sl, b.x + 1.0, b.cy, 1.1)
    icon_person(sl, b.x + 2.6, b.cy - 0.1, 1.0)
    icon_doc(sl, b.x + 3.7, b.cy, 0.8)


def build() -> Deck:
    d = Deck()
    d.cover("会議を30分で終える", "決めることを先に書けば短くなる",
            "これは見本です。今日は会議を短くする方法を、図で6枚にまとめてお話しします。"
            "話すのは5分ほどです。最後に、明日からやることを3つお渡しします。まずは、今の会議がどのくらい延びているかから見ていきます。", "最後に、明日からやること3つ", cover_art)

    # 根拠: 割合はマスで見せる
    sl = d.slide("会議の7割が、時間どおりに終わっていない",
                 "まず今の様子です。この四角ひとつが、会議の1割です。オレンジが、予定の時間を"
                 "過ぎた会議です。10個のうち7個がオレンジですね。つまり、だいたい7割の会議が延びています。"
                 "ここで大事なのは、延びることが珍しくない、ということです。")
    inner = sl.panel(CONTENT, "先月の定例会議（架空の例）", tag="根拠")
    ratio_grid(sl, Box(inner.x, inner.y + 0.2, inner.w, inner.h), 0.7,
               "10回のうち7回が延びた", "1マス＝会議の1割")
    sl.band("だから、延びる前提で、決めることを先に書く")
    sl.source(SRC)

    # 根拠: 数字の比較は棒
    sl = d.slide("議題を先に送ると、会議は短くなる",
                 "次に、議題を先に送った会議と、送らなかった会議を比べました。左が送らなかった会議で、"
                 "平均52分。右が送った会議で、平均31分です。棒の高さを見ると、半分くらいに"
                 "なっているのが分かります。ただし架空の数字なので、向きだけ受け取ってください。")
    inner = sl.panel(CONTENT, "会議の平均時間（分）", tag="根拠")
    bars(sl, Box(inner.x + 2, inner.y, inner.w - 4, inner.h), [
        ("議題なし", 52, "gray"), ("議題を前日に送る", 31, "accent")], unit="分")
    sl.band("だから、議題は前日までに送る")
    sl.source(SRC)

    # 手順はフロー
    sl = d.slide("会議は4つの手順で進める",
                 "では、どう進めるか。手順は4つです。左から、決めることを書く、資料を前日に送る、"
                 "当日は決めることから話す、最後に誰がいつまでに何をするかを確かめる。"
                 "オレンジの3つ目がいちばん効きます。最初の5分で、決めることを読み上げてください。")
    flow_steps(sl, Box(0.9, 2.0, 11.5, 3.0), [
        ("決めることを書く", "1行で書く"), ("前日に送る", "資料も一緒に"),
        ("決めることから話す", "最初の5分で読み上げ"), ("担当と期限を確かめる", "誰が・いつまでに")],
        focus=2)

    # 判断は問いの図
    sl = d.slide("3つの問いで、会議の形を決める",
                 "でも、全部を会議にする必要はありません。左の問いから順に見ます。メールで済むなら、"
                 "会議はしません。済まなくても、決める人が一人なら、その人と短く話せば足ります。"
                 "どちらでもなく、みんなで決めるときだけ、30分の会議を開きます。")
    boxes = decision_flow(sl, Box(0.8, 1.6, 11.7, 4.9),
                          ["メールで\n済む？", "決める人は\n一人？"],
                          ["メールにする", "その人と\n短く話す", "30分の\n会議を開く"])
    icon_doc(sl, boxes[0].cx, boxes[0].y + 1.9, 0.6)
    icon_person(sl, boxes[1].cx, boxes[1].y + 2.0, 0.6)
    icon_clock(sl, boxes[2].cx, boxes[2].y + 2.0, 0.6)

    # 前後の比較
    sl = d.slide("変えるのは、始め方だけ",
                 "変える前と後を並べます。左が今の会議で、近況の報告から始まり、決めることは"
                 "最後に回ります。右が変えた後で、決めることから始めます。真ん中の矢印のとおり、"
                 "変えるのは始め方だけです。中身や人数は変えなくて大丈夫です。")
    before_after(sl, Box(0.8, 1.6, 11.7, 4.0),
                 ("今", ["近況の報告から始める", "決めることは最後", "時間切れで持ち越し"]),
                 ("これから", ["決めることから始める", "報告は資料で読む", "残りで質問"]),
                 "始め方を変える")
    sl.band("だから、最初の5分で決めることを読み上げる")

    # 2x2
    sl = d.slide("急ぎで大事な議題だけ、会議で決める",
                 "議題の選び方です。横が急ぎかどうか、縦が大事かどうか。右上の、急ぎで大事な"
                 "ものだけを会議で決めます。左上の、大事だが急がないものは、次の定例に回します。"
                 "下の2つは、メールやチャットで済ませます。会議で決めるのは、右上の1マスだけです。")
    matrix_2x2(sl, Box(0.9, 1.6, 11.5, 4.9), ("急がない", "急ぐ"), ("大事でない", "大事"),
               ["次の定例へ", "会議で決める", "メールで済ます", "チャットで済ます"], focus=1)

    # 役割
    sl = d.slide("書記と時間係を、会議ごとに決める",
                 "会議には、進める人のほかに2つの役を置きます。書記は決まったことを書き、"
                 "時間係は残り時間を5分ごとに伝えます。役は毎回変えて、同じ人に偏らないようにします。"
                 "では、これをいつから始めるか。次で進め方を見ます。")
    role_cards(sl, Box(0.9, 2.0, 11.5, 4.3), [
        {"title": "進める人", "icons": ["person"], "rows": [("人", "議題を読む")]},
        {"title": "書記", "icons": ["doc"], "rows": [("人", "決まったことを書く")]},
        {"title": "時間係", "icons": ["clock"], "rows": [("人", "5分ごとに伝える")]}])

    # 時系列
    sl = d.slide("1か月で、全部の定例を切りかえる",
                 "進め方です。今週は自分の会議で試し、2週目にチームへ広げます。3週目に"
                 "結果を見て直し、4週目から全部の定例をこの形にします。"
                 "オレンジの1週目、つまり今週は、自分の会議ひとつだけで試せば十分です。"
                 "では最後に、明日からやることをまとめます。")
    timeline(sl, Box(0.9, 1.6, 11.5, 4.6), [
        ("1週目", "自分の会議で試す"), ("2週目", "チームへ広げる"),
        ("3週目", "結果を見て直す"), ("4週目", "全部の定例で使う")], focus=0)

    # 行動
    sl = d.slide("明日から、この3つをやる",
                 "最後に、明日からやることです。1つ目、決めることを1行で書く。2つ目、議題と資料を"
                 "前日に送る。3つ目、最初の5分で決めることを読み上げる。右に、もとにした"
                 "ページを書いておきました。まずは明日の会議ひとつから試してください。")
    action_list(sl, Box(0.8, 1.6, 11.7, 4.9), [
        ("決めることを1行で書く", "会議の案内の1行目に書く", "4枚目"),
        ("議題と資料を前日に送る", "当日の朝では遅い", "3枚目"),
        ("最初の5分で読み上げる", "報告は資料で読んでもらう", "6枚目")])

    # 記入用の表
    sl = d.slide("自分の会議を、この表に書き出す",
                 "持ち帰り用の表です。1行に1つの会議を書きます。決めること、形、書記、時間係を"
                 "埋めてください。空いた欄があれば、そこがまだ決まっていない所です。"
                 "今日の話は以上です。会議は、決めることを先に書けば短くなります。")
    table(sl, Box(0.8, 1.6, 11.7, 4.6), ["会議の名前", "決めること（1行）", "形", "書記", "時間係"],
          [["", "", "", "", ""] for _ in range(5)], [2, 4, 1.5, 1.3, 1.3])
    return d


if __name__ == "__main__":
    out = HERE / "sample_会議を30分で終える.pptx"
    build().save(str(out))
    print(out)
